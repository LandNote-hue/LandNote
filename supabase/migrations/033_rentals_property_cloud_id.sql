-- 매각 건물 기존 임대차 — 클라우드 매물 id 연결 + 권한 정합
-- 운영 적용은 배포 요청 시에만. 원격 DB에는 실행하지 않음.
-- 사전 진단(운영 자료 변경 없음): supabase/diagnostics/033_rentals_property_cloud_id.sql
-- 진단 SQL을 먼저 실행하고 결과를 파일로 보관한 뒤, 이 마이그레이션을 적용한다.
-- 중복 (user_id, local_id)가 있으면 unique index 생성 전에 실패한다. 행을 삭제하거나 임의 연결하지 않는다.
--
-- 사전 진단(읽기 전용, 별도 세션): supabase/diagnostics/033_rentals_property_cloud_id.sql
-- 진단 결과를 저장한 뒤에만 이 마이그레이션을 적용한다.
-- 중복 행을 삭제하거나, 후보가 여러 개인 임대차를 임의 연결하지 않는다.

alter table public.rentals
  add column if not exists property_id bigint,
  add column if not exists deleted_at timestamptz;

create index if not exists rentals_property_id_idx on public.rentals(property_id);
create index if not exists rentals_deleted_at_idx on public.rentals(deleted_at);

create table if not exists public.rentals_link_review (
  id bigint generated by default as identity primary key,
  rental_id bigint,
  pid bigint,
  user_id uuid,
  company_id uuid,
  reason text not null,
  candidate_property_ids bigint[],
  created_at timestamptz not null default now()
);

alter table public.rentals_link_review enable row level security;

-- pid = 매물 local_id (001_initial). 클라우드 properties.id 와 조인하지 않음.
-- 소유자·회사가 같고 local_id가 유일한 건만 연결. 0건·다중 후보는 건너뛴다.
update public.rentals r
set property_id = p.id
from public.properties p
where r.property_id is null
  and r.pid is not null
  and p.user_id = r.user_id
  and p.company_id is not distinct from r.company_id
  and p.local_id = r.pid
  and (
    select count(*)
    from public.properties p2
    where p2.user_id = r.user_id
      and p2.company_id is not distinct from r.company_id
      and p2.local_id = r.pid
  ) = 1;

do $$
declare
  dup_n int;
begin
  select count(*) into dup_n
  from (
    select user_id, local_id
    from public.rentals
    where local_id is not null
    group by user_id, local_id
    having count(*) > 1
  ) d;
  if dup_n > 0 then
    raise exception
      'rentals: % duplicate (user_id, local_id) group(s). Re-run supabase/diagnostics/033_rentals_property_cloud_id.sql in a separate session; do not delete rows here.',
      dup_n;
  end if;
  create unique index if not exists rentals_user_local_id_unique
    on public.rentals (user_id, local_id)
    where local_id is not null;
end $$;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'rentals_property_id_fkey'
  ) then
    alter table public.rentals
      add constraint rentals_property_id_fkey
      foreign key (property_id) references public.properties(id) on delete cascade;
  end if;
end $$;

drop policy if exists "rentals_select_rbac" on public.rentals;
drop policy if exists "rentals_write_rbac" on public.rentals;

create policy "rentals_select_rbac" on public.rentals
  for select using (
    company_id = public.current_company_id()
    and (
      public.is_company_ceo()
      or user_id = auth.uid()
      or exists (
        select 1 from public.properties pr
        where pr.id = rentals.property_id
          and pr.company_id is not distinct from rentals.company_id
          and public.can_read_shareable_row(pr.user_id, pr.company_id, 'properties')
      )
    )
  );

-- 매물과 동일: 소유자·대표·공유 수정 권한. WITH CHECK도 같게 맞춤.
-- 부모 매물은 같은 소유자·회사여야 함 (다른 회사 매물 연결 금지).
create policy "rentals_write_rbac" on public.rentals
  for all using (
    public.can_write_shareable_row(user_id, company_id, 'properties')
  ) with check (
    public.can_write_shareable_row(user_id, company_id, 'properties')
    and company_id = public.current_company_id()
    and (
      property_id is null
      or exists (
        select 1 from public.properties pr
        where pr.id = rentals.property_id
          and pr.user_id = rentals.user_id
          and pr.company_id is not distinct from rentals.company_id
      )
    )
  );
